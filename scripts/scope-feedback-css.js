// Builds src/feedback/generated/feedback.scoped.css from Bootstrap 4 and src/feedback/styles.css.
// Every rule is prefixed with .fb-app, so the feedback form and admin styles only apply inside the
// feedback wrapper (src/feedback/FeedbackShell.js) and never restyle the event pages.
// Runs automatically before npm start and npm run build. Edit src/feedback/styles.css, not the output.
const fs = require("fs");
const path = require("path");
const postcss = require("postcss");

const SCOPE = ".fb-app";
const root = path.join(__dirname, "..");
const sources = [
  require.resolve("bootstrap/dist/css/bootstrap.min.css", { paths: [root] }),
  path.join(root, "src", "feedback", "styles.css"),
];
const outDir = path.join(root, "src", "feedback", "generated");
const outFile = path.join(outDir, "feedback.scoped.css");

function scopeSelector(selector) {
  const sel = selector.trim();
  // The page level rules of the standalone app now apply to the wrapper element.
  if (sel === "html" || sel === "body" || sel === ":root") return SCOPE;
  // For example "html [type=button]" becomes ".fb-app [type=button]".
  const pageLevel = sel.match(/^(?:html|body|:root)(?=[\s.[:#>+~])(.*)$/);
  if (pageLevel) return `${SCOPE}${pageLevel[1]}`;
  // Bootstrap puts .modal-open on the body element while a modal is open, see components/Modal.js.
  if (sel === ".modal-open") return "body.modal-open";
  if (sel.startsWith(".modal-open ")) return `body.modal-open ${SCOPE} ${sel.slice(".modal-open ".length)}`;
  return `${SCOPE} ${sel}`;
}

const scoper = {
  postcssPlugin: "scope-feedback",
  Once(css) {
    // Source map links point at files that are not shipped, and @page would apply to every page when printing.
    css.walkComments((c) => c.remove());
    css.walkAtRules("page", (a) => a.remove());
    css.walkRules((rule) => {
      const parent = rule.parent;
      if (parent && parent.type === "atrule" && /keyframes$/i.test(parent.name)) return;
      rule.selectors = rule.selectors.map(scopeSelector);
      // overflow-x on a wrapper div would turn it into a scroll container and break sticky headers,
      // so the standalone app's body overflow rule is applied to the real body by FeedbackShell instead.
      if (rule.selector === SCOPE) rule.walkDecls("overflow-x", (d) => d.remove());
    });
  },
};

const input = sources.map((file) => fs.readFileSync(file, "utf8")).join("\n");
const header =
  "/* Generated by scripts/scope-feedback-css.js, do not edit. Edit src/feedback/styles.css instead. */\n" +
  `${SCOPE} { min-height: 100vh; }\n` +
  "body.fb-active { overflow-x: hidden; }\n";

postcss([scoper])
  .process(input, { from: undefined })
  .then((result) => {
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(outFile, header + result.css);
    console.log(`Scoped feedback styles written to ${path.relative(root, outFile)}`);
  })
  .catch((err) => {
    console.error("Could not build the scoped feedback styles:", err);
    process.exit(1);
  });
